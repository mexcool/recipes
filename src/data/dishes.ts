/**
 * Seed dish book. A dish is a SHAPE over slot roles: it names which foods it suits for each role and how
 * to cook them, never how much. Steps use {{role}} placeholders that render as "the chosen food + her
 * amount". Every dish here was validated against the demo plan's templates (see dishes.test.ts).
 */
import type { Dish, DishBinding } from '@/core/model';

type DishInput = Omit<
  Dish,
  'origin' | 'status' | 'tags' | 'lunchboxOk' | 'mealTypes' | 'freeVeg' | 'condiments' | 'methods'
> &
  Partial<
    Pick<
      Dish,
      'origin' | 'status' | 'tags' | 'lunchboxOk' | 'mealTypes' | 'freeVeg' | 'condiments' | 'methods'
    >
  >;

const dish = (x: DishInput): Dish => ({
  origin: 'seed',
  status: 'approved',
  tags: [],
  lunchboxOk: false,
  mealTypes: ['pranzo', 'cena'],
  freeVeg: [],
  condiments: [],
  methods: [],
  ...x,
});

const b = (
  role: DishBinding['role'],
  foods: DishBinding['foods'],
  prep = '',
  pot: DishBinding['pot'] = 'separate',
): DishBinding => ({ role, foods, prep, pot });

